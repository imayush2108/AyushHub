export function getSongById(id) {
  return songsData.find(song => song.id === id);
}

export function getNextPrevSong(id) {
  const index = songsData.findIndex(song => song.id === id);
  if (index === -1) return { prevSong: null, nextSong: null };
  const prevIndex = (index - 1 + songsData.length) % songsData.length;
  const nextIndex = (index + 1) % songsData.length;
  return {
    prevSong: songsData[prevIndex],
    nextSong: songsData[nextIndex]
  };
}

export function getRelatedSongs(id, limit = 4) {
  const current = getSongById(id);
  if (!current) return songsData.slice(0, limit);
  return songsData
    .filter(song => song.id !== id)
    .sort((a, b) => {
      // Prioritize same category or artist
      const aScore = (a.category === current.category ? 2 : 0) + (a.artistTag === current.artistTag ? 2 : 0);
      const bScore = (b.category === current.category ? 2 : 0) + (b.artistTag === current.artistTag ? 2 : 0);
      return bScore - aScore;
    })
    .slice(0, limit);
}
